#!/usr/bin/env python3
"""Import every b1.7.3 sound into mc-rs.

usage: python3 tools/gen_sounds.py <decompiled>/minecraft   (the dir holding game/ and src/)

Reads game/assets/indexes/b1.7.json, copies each .ogg to mc-rs/assets/sound/<index path> and writes
mc-rs/src/audio/table.rs. Names follow `SoundPool.addSound` / `Minecraft.installResource`:
  sound/ + newsound/  -> effects: extension cut, trailing digits stripped, '/' -> '.', one key holds all variants
  music/ + newmusic/  -> background tracks, one random pick from the whole list
  streaming/*.ogg     -> jukebox records (key keeps its digits: "13", "cat")
The 12 streaming/*.mus files are not imported: b1.7.3 only has records 13 and cat (`Item.record13` / `recordCat`).
The block -> StepSound table is read from `Block.java` (`setStepSound`), the three StepSound flavours from its first lines.
"""
import glob, json, os, re, shutil, sys

src = sys.argv[1] if len(sys.argv) > 1 else "."
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mc-rs")
objs = json.load(open(f"{src}/game/assets/indexes/b1.7.json"))["objects"]

def key(path, strip_digits=True):
    n = path.split("/", 1)[1]
    n = n[: n.index(".")]
    if strip_digits:
        n = n.rstrip("0123456789")
    return n.replace("/", ".")

sfx, music, rec = {}, [], {}
for path, o in sorted(objs.items()):
    if not path.endswith(".ogg"):
        continue
    if re.match(r"newsound/mob/wolf/(bark|death|growl|hurt|panting|whine)\d*\.ogg$", path):
        continue  # NOT b1.7.3: the wolf's cries are the voices below
    h = o["hash"]
    dst = f"{root}/assets/sound/{path}"
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(f"{src}/game/assets/objects/{h[:2]}/{h}", dst)
    inc = f'include_bytes!("../../assets/sound/{path}")'
    top = path.split("/")[0]
    if top in ("sound", "newsound"):
        sfx.setdefault(key(path), []).append(inc)
    elif top in ("music", "newmusic"):
        music.append(inc)
    elif top == "streaming":
        rec.setdefault(key(path, False), []).append(inc)

# NOT b1.7.3: the wolf voices (`wolf.zip`, 1.21.5's sound variants; the baby set is not used): assets/sound/wolf/<voice>/<cry><n>.ogg -> "mob.wolf.<voice>.<cry>".
for p in sorted(glob.glob(f"{root}/assets/sound/wolf/*/*.ogg")):
    voice, f = p.split("/")[-2:]
    sfx.setdefault(f"mob.wolf.{voice}.{f.split('.')[0].rstrip('0123456789')}", []).append(f'include_bytes!("../../assets/sound/wolf/{voice}/{f}")')

# Block.java: `new Xxx(<id>` ... `.setStepSound(<field>)`; BlockCloth() has no id argument (35, wool).
SOUNDS = ["soundPowderFootstep", "soundWoodFootstep", "soundGravelFootstep", "soundGrassFootstep", "soundStoneFootstep",
          "soundMetalFootstep", "soundGlassFootstep", "soundClothFootstep", "soundSandFootstep"]
step = {}
for l in open(f"{src}/src/net/minecraft/src/Block.java"):
    s = re.search(r"setStepSound\((\w+)\)", l)
    if not s or "public static final" not in l:
        continue
    m = re.search(r"new \w+\((\d+)", l)
    step[int(m.group(1)) if m else 35] = SOUNDS.index(s.group(1))
assert len(step) == 83, len(step)

o = ["// Generated by tools/gen_sounds.py from the b1.7.3 asset index; do not edit.", ""]
o.append("/// `SoundPool` key -> every variant (one is picked at random per play).")
o.append("pub static SFX: &[(&str, &[&[u8]])] = &[")
for k, v in sorted(sfx.items()):
    o.append(f'    ("{k}", &[{", ".join(v)}]),')
o += ["];", "", "/// `soundPoolMusic`: `music/` + `newmusic/`, played at random between 10 and 20 minutes apart.",
      "pub static MUSIC: &[&[u8]] = &[", *[f"    {m}," for m in music], "];", "",
      "/// `soundPoolStreaming`: the jukebox records, by `ItemRecord.recordName`.", "pub static RECORDS: &[(&str, &[u8])] = &["]
o += [f'    ("{k}", {v[0]}),' for k, v in sorted(rec.items())]
o += ["];", "", "/// `Block.setStepSound` per block id: index into `audio::STEP` (0 powder, 1 wood, 2 gravel, 3 grass, 4 stone, 5 metal, 6 glass, 7 cloth, 8 sand).",
      "/// Blocks not listed use `Block.soundPowderFootstep` (the field's default).",
      "pub static BLOCK_STEP: &[(u8, u8)] = &[", "    " + ", ".join(f"({i}, {s})" for i, s in sorted(step.items())) + ",", "];", ""]
open(f"{root}/src/audio/table.rs", "w").write("\n".join(o))
print(f"{sum(map(len, sfx.values()))} effects in {len(sfx)} keys, {len(music)} music, {len(rec)} records, {len(step)} step blocks")
