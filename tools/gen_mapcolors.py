"""Writes mc-rs/src/world/mapcolors.rs: per block id the `MapColor` index of its material, whether the material is a liquid and the
block's light opacity, all read from the real b1.7.3 classes (`tools/golden/MapTab.java`).
Run from the repo root with the decompiled tree next to it:  python3 tools/gen_mapcolors.py [path/to/minecraft/bin]
Needs a JDK with jdk.compiler (Java 21)."""
import os, subprocess, sys, tempfile

bin_dir = sys.argv[1] if len(sys.argv) > 1 else "minecraft/bin"
with tempfile.TemporaryDirectory() as t:
    os.makedirs(t + "/out")
    subprocess.run(["java", "-m", "jdk.compiler/com.sun.tools.javac.Main", "-nowarn", "-cp", bin_dir, "-d", t + "/out", "tools/golden/MapTab.java"], check=True)
    # `StringTranslate` fails on a missing resource: empty lang files, like tools/golden/README.md.
    os.makedirs(t + "/res/lang")
    for f in ("en_US.lang", "stats_US.lang"):
        open(f"{t}/res/lang/{f}", "w").close()
    out = subprocess.run(["java", "-cp", f"{t}/out:{t}/res:{bin_dir}", "MapTab"], check=True, capture_output=True, text=True).stdout
rows = [list(map(int, l.split())) for l in out.splitlines() if l[:1].isdigit() and len(l.split()) == 4]
assert [r[0] for r in rows] == list(range(256)), "one line per block id"
colors = [r[1] for r in rows]
liquid = [r[2] for r in rows]
opacity = [max(r[3], 0) for r in rows]  # a null block (-1) is 0
def arr(name, doc, v):
    body = ",\n".join("    " + ", ".join(f"{x:3}" for x in v[i:i + 16]) for i in range(0, 256, 16))
    return f"/// {doc}\npub const {name}: [u8; 256] = [\n{body},\n];\n\n"
rs = "//! GENERATED by tools/gen_mapcolors.py from the b1.7.3 classes (tools/golden/MapTab.java): what `ItemMap` reads of a block.\n\n"
rs += arr("COLOR", "`Block.blockMaterial.materialMapColor.colorIndex` (0 air, 1 grass, 2 sand, 3 cloth, 4 tnt, 5 ice, 6 iron, 7 foliage, 8 snow, 9 clay, 10 dirt, 11 stone, 12 water, 13 wood); an empty id is 0.", colors)
rs += arr("LIQUID", "`Block.blockMaterial.getIsLiquid()` as 0 / 1.", liquid)
rs += "/// `Block.lightOpacity` (what `Chunk.generateHeightMap` tests); an empty id is 0.\n" + arr("OPACITY", "", opacity).split("\n", 1)[1]
open("mc-rs/src/world/mapcolors.rs", "w").write(rs)
print("mapcolors.rs written")
