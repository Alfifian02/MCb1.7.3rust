#!/usr/bin/env python3
"""Rewrites mc-rs/assets/items.rgba (b1.7.3's gui/items.png, 256x256, 16x16 sprites) from Bedrock Developer Art (midnightcherry, v2.6.6,
textures/items/*.png). Companion of gen_terrain_bedrock.py. Run from the repo root:
    python3 tools/gen_items_bedrock.py "Bedrock_Developer_Art.zip"      (or the unzipped folder; needs Pillow)
One table, item id -> Bedrock name; the tile of each id is `Item.iconIndex` (`render/icons.rs`, generated by gen_terrain.py). Dyes cover all
16 damages (`atlas::item_icon_dmg`: tile 78 + (d % 8) * 16 + d / 8). Notes / left alone ON PURPOSE:
  * tile 54 (compass) and 70 (clock): `render/anim.rs` draws the needle over a PLAIN icon and paints the dial into the clock's magenta
    face; the pack's frames already carry a needle / a finished face and would show twice or never turn.
  * leather armor is multiplied by the default dye colour 0xA06540 (the pack's sprites are grey).
  * every tile that is not a b1.7.3 item (Cortes Combat 208..=232, bandage 234, ...): they are generated by their own tools.
LICENCE: the pack's licence.txt allows private use and modification only; do NOT commit or redistribute the generated items.rgba.
"""
import io, os, sys, zipfile
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else "Bedrock_Developer_Art.zip"
OUT = "mc-rs/assets/items.rgba"

if os.path.isdir(SRC):
    TEX = next(r for r, _, f in os.walk(SRC) if r.replace("\\", "/").endswith("textures/blocks") and "stone.png" in f)[: -len("blocks")]
    def read(p):
        try:
            return open(os.path.join(TEX, *p.split("/")), "rb").read()
        except FileNotFoundError:
            raise KeyError(p)
else:
    z = zipfile.ZipFile(SRC)
    names = {n.replace("\\", "/"): n for n in z.namelist()}
    ROOT = next(n for n in names if n.endswith("textures/blocks/stone.png"))[: -len("blocks/stone.png")]
    def read(p):
        return z.read(names[ROOT + p])


def itm(name):
    """An item texture as 16x16: animation strips give their first frame, bigger sheets are box-filtered down."""
    im = Image.open(io.BytesIO(read("items/" + name + ".png"))).convert("RGBA")
    w = im.width
    if im.height != w:
        im = im.crop((0, 0, w, w))
    return im if w == 16 else im.resize((16, 16), Image.BOX)


items = Image.frombytes("RGBA", (256, 256), open(OUT, "rb").read())  # tiles without a counterpart stay as they are

