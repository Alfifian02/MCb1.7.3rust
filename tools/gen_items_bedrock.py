# armor: leather 298.., chain 302.., iron 306.., diamond 310.., gold 314..; helmet, chestplate, leggings, boots = tile 0, 16, 32, 48 + column 0..4
for col, (mat, ida) in enumerate((("leather", 298), ("chainmail", 302), ("iron", 306), ("diamond", 310), ("gold", 314))):
    for row, piece in enumerate(("helmet", "chestplate", "leggings", "boots")):
        TABLE.append((ida + row, col + row * 16, f"{mat}_{piece}"))
# dyes: damage 0..15 = ink, rose red, cactus green, cocoa, lapis, purple, cyan, light gray, gray, pink, lime, dandelion, light blue, magenta, orange, bone meal
DYES = ["black", "red", "green", "brown", "blue", "purple", "cyan", "silver", "gray", "pink", "lime", "yellow", "light_blue", "magenta", "orange", "white"]
for d, c in enumerate(DYES):
    TABLE.append((351, 78 + (d % 8) * 16 + d // 8, "dye_powder_" + c))

missing = []
for item_id, tile, name in sorted(TABLE, key=lambda t: t[1]):
    try:
        im = itm(name)
    except KeyError:
        missing.append((item_id, name))
        continue
    if name.startswith("leather_"):  # Bedrock's leather armor is grey (dyed at draw time); a sprite here is not, so apply the default 0xA06540
        px = im.load()
        for y in range(16):
            for x in range(16):
                r, g, b, a = px[x, y]
                px[x, y] = (r * 0xA0 // 255, g * 0x65 // 255, b * 0x40 // 255, a)
    items.paste(im, ((tile % 16) * 16, (tile // 16) * 16))

open(OUT, "wb").write(items.tobytes())
print("wrote", OUT, "sprites from the pack:", len(TABLE) - len(missing))
if missing:
    print("NOT FOUND in the pack (tile kept):", missing)
