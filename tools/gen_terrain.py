#!/usr/bin/env python3
"""Writes mc-rs/assets/terrain.rgba: the real b1.7.3 terrain.png (256x256, 16x16 tiles of 16x16) as raw RGBA, UNTINTED (grass, foliage and the
biome tint are applied per vertex by the mesher, `world/climate.rs`);
also writes grasscolor.rgb, foliagecolor.rgb, items.rgba (gui/items.png) and src/render/icons.rs (item id -> items.png tile). Run from the repo root: python3 tools/gen_terrain.py  (needs Pillow; reads minecraft/jars/deobfuscated.jar).
ponytail: one climate for the whole world (temperature 0.8, rainfall 0.4, plains); biome tint per block needs a colour
vertex attribute, which is the upgrade path. Tile 255 (unused in the png) holds birch leaves."""
import io, zipfile
from PIL import Image

z = zipfile.ZipFile("minecraft/jars/deobfuscated.jar")
png = lambda n: Image.open(io.BytesIO(z.read(n))).convert("RGBA")
terrain, grass, foliage = png("terrain.png"), png("misc/grasscolor.png"), png("misc/foliagecolor.png")

def tile(n): return terrain.crop(((n % 16) * 16, (n // 16) * 16, (n % 16) * 16 + 16, (n // 16) * 16 + 16)).copy()
def put(n, im): terrain.paste(im, ((n % 16) * 16, (n // 16) * 16))
def opaque(im): im.putalpha(255); return im

put(255, tile(53))                                        # birch leaves: same grey tile as 53, tinted BIRCH by the mesher
for n in (237, 67): put(n, opaque(tile(n)))               # lava, ice are drawn as opaque cubes; water keeps its alpha (0.54, drawn translucent)
open("mc-rs/assets/terrain.rgba", "wb").write(terrain.tobytes())
open("mc-rs/assets/grasscolor.rgb", "wb").write(grass.convert("RGB").tobytes())
open("mc-rs/assets/foliagecolor.rgb", "wb").write(foliage.convert("RGB").tobytes())
open("mc-rs/assets/items.rgba", "wb").write(png("gui/items.png").tobytes())
# art/kz.png (painting motives, 256x256), item/sign.png (64x32, the sign model) and mob/char.png (64x32, the player skin) under it, 256x320: `render::atlas::ART`
# From row 288 on, 64 x 32 skins four to a row (`render::atlas::skin_px`): slot 0 mob/char.png, 1..=10 armor/<cloth, chain, iron, diamond, gold>_<1, 2>.png
# (slot 1 + 2 * material + layer - 1), 11.. the mobs in `SKINS` order; 28 slots = 7 bands, 512 rows in all.
SKINS = ["char"] + [f"armor/{m}_{i}" for m in ("cloth", "chain", "iron", "diamond", "gold") for i in (1, 2)] + [
    f"mob/{n}" for n in ("pig", "cow", "chicken", "sheep", "sheep_fur", "wolf", "wolf_tame", "wolf_angry", "squid", "zombie", "pigzombie", "skeleton", "creeper", "spider", "slime", "ghast", "ghast_fire")]
SKINS[0] = "mob/char"
art = Image.new("RGBA", (256, 288 + 32 * ((len(SKINS) + 3) // 4)), (0, 0, 0, 0))
art.paste(png("art/kz.png"), (0, 0))
art.paste(png("item/sign.png"), (0, 256))
for n, name in enumerate(SKINS):
    assert png(name + ".png").size == (64, 32), name
    art.paste(png(name + ".png"), ((n % 4) * 64, 288 + (n // 4) * 32))
open("mc-rs/assets/art.rgba", "wb").write(art.tobytes())

# item id -> items.png tile, from Item.java: `new ItemX(<id - 256>, ...).setIconCoord(col, row)` or `.setIconIndex(n)`
import re
src = open("minecraft/src/net/minecraft/src/Item.java").read()
icons = {}
for m in re.finditer(r"= \(new \w+\((\d+)[^;]*?\.setIcon(Coord|Index)\((\d+)(?:, (\d+))?\)", src):
    n = int(m.group(3)) + (int(m.group(4)) * 16 if m.group(2) == "Coord" else 0)
    icons[256 + int(m.group(1))] = n
rs = "//! GENERATED by tools/gen_terrain.py: `Item.iconIndex` of every item (id, items.png tile), sorted by id.\npub const ICONS: &[(u16, u8)] = &[\n"
rs += "".join(f"    ({k}, {v}),\n" for k, v in sorted(icons.items())) + "];\n"
open("mc-rs/src/render/icons.rs", "w").write(rs)
print(len(icons), "item icons")
# misc/dial.png (16x16): the sky painted into the clock face by `render::anim` (TextureWatchFX)
open("mc-rs/assets/dial.rgba", "wb").write(png("misc/dial.png").tobytes())
