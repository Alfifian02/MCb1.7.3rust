#!/usr/bin/env python3
"""Controlify's contextual button guide (isXander, LGPL-3.0-or-later) -> `mc-rs/src/input/guide_rules.rs`.

Reads `assets/controlify/contextual/{guide,facts}/{in_game,container}.json` and `lang/en_us.json` and writes the rules and the fact
definitions as Rust statics, in the file's own order (the order is the precedence: the first matching rule of a (binding, side) key wins).
The predicates keep Controlify's vocabulary (`minecraft:chest`, `#minecraft:doors`, `minecraft:charged_projectiles`...): `src/input/guide.rs`
resolves those names against b1.7.3's ids, and a name this game has no equivalent of simply never matches (the rule is kept, off).

Usage: gen_guide.py <Controlify-main/src/main/resources/assets/controlify> [out.rs]
"""
import json
import sys

root = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "mc-rs/src/input/guide_rules.rs"
lang = json.load(open(f"{root}/lang/en_us.json"))
VANILLA = {"key.jump": "Jump"}  # vanilla keys the rules reuse


def short(i):
    """`controlify:jump` -> `jump`; `minecraft:chest` stays (the game names are matched whole)."""
    return i.split(":", 1)[1] if i.startswith("controlify:") else i


def s(x):
    return json.dumps(x, ensure_ascii=True)


def strs(v):
    v = [v] if isinstance(v, str) else list(v)
    return "&[" + ", ".join(s(x) for x in v) + "]"


def item(d):
    count = d.get("count", {}).get("min", 0)
    preds = list(d.get("predicates", {}).keys())
    empty = [k for k, v in d.get("components", {}).items() if v == []]
    return f"ItemSpec {{ items: {strs(d.get('items', []))}, count_min: {count}, preds: {strs(preds)}, empty_comps: {strs(empty)} }}"


def block(d):
    st = d.get("state", {}).get("open")
    op = "None" if st is None else f"Some({st})"
    return f"BlockSpec {{ blocks: {strs(d.get('blocks', []))}, open: {op} }}"


def entity(d):
    flags = ", ".join(f"({s(k)}, {'true' if v else 'false'})" for k, v in d.get("flags", {}).items())
    veh = "None"
    if "vehicle" in d:
        veh = f"Some(&{entity(d['vehicle'])})"
    eq = d.get("equipment", {})
    saddle = "true" if "saddle" in eq else "false"
    body = strs(eq.get("body", {}).get("items", []))
    return (f"EntitySpec {{ types: {strs(d.get('type', []))}, flags: &[{flags}], game_modes: {strs(d.get('game_mode', []))}, "
            f"vehicle: {veh}, saddle: {saddle}, body_items: {body} }}")


def pred(p):
    if isinstance(p, bool):
        return f"Pred::Static({'true' if p else 'false'})"
    if isinstance(p, str):
        return f"Pred::Fact({s(short(p))})"
    if "fact" in p:
        return f"Pred::Fact({s(short(p['fact']))})"
    if "slot" in p:
        slot = s(short(p["slot"]))
        if "item" in p:
            return f"Pred::Item {{ slot: {slot}, spec: {item(p['item'])} }}"
        if "block" in p:
            return f"Pred::Block {{ slot: {slot}, spec: {block(p['block'])} }}"
        if "entity" in p:
            return f"Pred::Entity {{ slot: {slot}, spec: {entity(p['entity'])} }}"
        raise SystemExit(f"unknown slot predicate {p}")
    sel = {k: p.get(k, []) for k in ("all_of", "none_of", "any_of")}
    if not any(k in p for k in sel):
        raise SystemExit(f"unknown predicate {p}")
    f = lambda xs: "&[" + ", ".join(pred(x) for x in xs) + "]"
    return f"Pred::Compound {{ all: {f(sel['all_of'])}, none: {f(sel['none_of'])}, any: {f(sel['any_of'])} }}"


def text(then):
    k = then["translate"]
    t = lang.get(k) or VANILLA.get(k)
    if t is None:
        raise SystemExit(f"no English text for {k}")
    return t


def rules(name, ident):
    rs = json.load(open(f"{root}/contextual/guide/{name}.json"))["rules"]
    lines = [f"pub static {ident}_RULES: &[Rule] = &["]
    for r in rs:
        left = "true" if r["where"] == "left" else "false"
        lines.append(f"    Rule {{ bind: {s(short(r['for']))}, left: {left}, when: {pred(r['if'])}, text: {s(text(r['then']))} }},")
    lines.append("];\n")
    return "\n".join(lines)


def facts(name, ident):
    fs = json.load(open(f"{root}/contextual/facts/{name}.json"))
    lines = [f"pub static {ident}_FACTS: &[(&str, Pred)] = &["]
    for k, v in fs.items():
        lines.append(f"    ({s(short(k))}, {pred(v)}),")
    lines.append("];\n")
    return "\n".join(lines)


with open(out, "w") as f:
    f.write("//! GENERATED by `tools/gen_guide.py` from Controlify's `contextual/{guide,facts}/*.json` (LGPL-3.0-or-later, isXander). Do not edit.\n")
    f.write("//! Rule order is precedence; texts are `en_us.json`'s.\n\n")
    f.write("use super::guide::{BlockSpec, EntitySpec, ItemSpec, Pred, Rule};\n\n")
    f.write(rules("in_game", "IN_GAME"))
    f.write(rules("container", "CONTAINER"))
    f.write(facts("in_game", "IN_GAME"))
    f.write(facts("container", "CONTAINER"))
print("ok ->", out)
