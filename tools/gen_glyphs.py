#!/usr/bin/env python3
"""Controlify's controller glyph fonts (isXander, LGPL-3.0-or-later) -> `mc-rs/assets/padbtn.rgba` + `mc-rs/src/input/glyph_map.rs`.

Each controller type is one bitmap font in Controlify: `font/controller/<t>.json` lists the characters of the 16 x 16 cells of
`textures/font/controller/<file>.png`, and `controllers/font_mappings/<t>.json` says which character is which input
(`controlify:button/south` ...). Here every type gets 32 cells (slot = character code - 1) in a 256 x 288 block of the HUD texture,
14 cells to a row on an 18 texel pitch: the glyph at +1, a transparent texel on each side so the sharp bilinear never reads the neighbour.

The table written next to it says, for each type and input, the cell and the glyph's advance (`BitmapProvider`: the used width + 1).

Usage: gen_glyphs.py <Controlify-main/src/main/resources/assets/controlify> [assets/padbtn.rgba] [src/input/glyph_map.rs]
"""
import json
import sys
from PIL import Image

root = sys.argv[1]
out_png = sys.argv[2] if len(sys.argv) > 2 else "mc-rs/assets/padbtn.rgba"
out_rs = sys.argv[3] if len(sys.argv) > 3 else "mc-rs/src/input/glyph_map.rs"

# (label, font json / mapping name): the order is `STYLES` in gamepad.rs, then Text.
TYPES = [("Xbox", "xbox_one"), ("PlayStation 5", "dualsense"), ("PlayStation 4", "dualshock4"), ("PlayStation 3", "dualshock3"),
         ("Switch", "switch"), ("Steam", "steam_deck"), ("Generic", "default")]
COLS, PITCH, CELLS = 14, 18, 32
H = (len(TYPES) * CELLS // COLS) * PITCH
assert len(TYPES) * CELLS % COLS == 0
sheet = Image.new("RGBA", (256, H), (0, 0, 0, 0))

# every input any type names, in a fixed order
names = []
maps = {}
for _, t in TYPES:
    m = json.load(open(f"{root}/controllers/font_mappings/{t}.json"))
    m.pop("unknown", None)
    maps[t] = m
    for k in m:
        if k not in names:
            names.append(k)
names.sort()

cell = [[-1] * len(names) for _ in TYPES]
adv = [[0] * len(names) for _ in TYPES]
for ti, (label, t) in enumerate(TYPES):
    font = json.load(open(f"{root}/font/controller/{t}.json"))["providers"][0]
    png = Image.open(f"{root}/textures/font/controller/{font['file'].split('/')[-1]}").convert("RGBA")
    assert font["height"] == 16 and font["ascent"] == 11, (t, font["height"], font["ascent"])
    pos = {}  # character code -> (row, col) in the png
    for r, row in enumerate(font["chars"]):
        for c, ch in enumerate(row):
            if ord(ch):
                pos[ord(ch)] = (r, c)
    for ni, name in enumerate(names):
        if name not in maps[t]:
            continue
        code = ord(maps[t][name])
        r, c = pos[code]
        g = png.crop((c * 16, r * 16, c * 16 + 16, r * 16 + 16))
        bbox = g.getbbox()
        assert bbox, (t, name)
        n = ti * CELLS + code - 1
        assert code - 1 < CELLS
        sheet.paste(g, ((n % COLS) * PITCH + 1, (n // COLS) * PITCH + 1))
        cell[ti][ni] = code - 1
        adv[ti][ni] = bbox[2] + 1  # the rightmost used column + 1, plus the pixel BitmapProvider adds

open(out_png, "wb").write(sheet.tobytes())
with open(out_rs, "w") as f:
    f.write("//! GENERATED by `tools/gen_glyphs.py` from Controlify's controller fonts (LGPL-3.0-or-later, isXander). Do not edit.\n\n")
    f.write(f"/// The controller types, in `STYLES` order (the picture styles; the Text style comes after them).\npub const TYPES: [&str; {len(TYPES)}] = [{', '.join(json.dumps(l) for l, _ in TYPES)}];\n")
    f.write(f"/// Cells per type in the block, 14 to a row on an 18 texel pitch.\npub const CELLS: usize = {CELLS};\npub const COLS: usize = {COLS};\npub const PITCH: usize = {PITCH};\n")
    f.write(f"/// Height of the block in texels (the HUD texture's `PAD_H`).\npub const BLOCK_H: usize = {H};\n\n")
    f.write(f"/// The inputs the fonts name (`controlify:` left off), sorted.\npub const INPUTS: [&str; {len(names)}] = [\n")
    for n in names:
        f.write(f"    {json.dumps(n.split(':', 1)[1])},\n")
    f.write("];\n\n")
    f.write("/// `CELL[type][input]`: the glyph's cell in the type's 32 (character code - 1), or -1 where the type has no picture for the input.\n")
    f.write(f"pub const CELL: [[i8; {len(names)}]; {len(TYPES)}] = [\n")
    for row in cell:
        f.write("    [" + ", ".join(str(x) for x in row) + "],\n")
    f.write("];\n\n")
    f.write("/// `ADVANCE[type][input]`: the width the glyph takes in a line of text, in GUI units.\n")
    f.write(f"pub const ADVANCE: [[u8; {len(names)}]; {len(TYPES)}] = [\n")
    for row in adv:
        f.write("    [" + ", ".join(str(x) for x in row) + "],\n")
    f.write("];\n")
print("block", 256, "x", H, "->", out_png, "|", len(names), "inputs ->", out_rs)
