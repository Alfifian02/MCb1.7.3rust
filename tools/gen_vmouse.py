#!/usr/bin/env python3
"""Controlify's `textures/gui/virtual_mouse.png` (32 x 32, LGPL-3.0-or-later, isXander) -> `mc-rs/src/input/vmouse_cursor.rs`.

The cursor is drawn as horizontal runs of one colour (one HUD quad each), so it needs no atlas block. Texels with alpha < 12 (an invisible shadow edge) are dropped.
Usage: gen_vmouse.py <virtual_mouse.png> [out.rs]
"""
import sys
from PIL import Image

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "mc-rs/src/input/vmouse_cursor.rs"
im = Image.open(src).convert("RGBA")
assert im.size == (32, 32), im.size
runs = []
for y in range(32):
    x = 0
    while x < 32:
        p = im.getpixel((x, y))
        if p[3] < 12:
            x += 1
            continue
        n = 1
        while x + n < 32 and im.getpixel((x + n, y)) == p:
            n += 1
        runs.append((x, y, n, p))
        x += n
with open(out, "w") as f:
    f.write("//! GENERATED by `tools/gen_vmouse.py` from Controlify's `virtual_mouse.png` (LGPL-3.0-or-later, isXander). Do not edit.\n\n")
    f.write("/// (x, y, length, [r, g, b, a]) of each horizontal run of one colour, in the texture's 32 x 32 texels.\n")
    f.write(f"pub const RUNS: [(u8, u8, u8, [u8; 4]); {len(runs)}] = [\n")
    for x, y, n, p in runs:
        f.write(f"    ({x}, {y}, {n}, [{p[0]}, {p[1]}, {p[2]}, {p[3]}]),\n")
    f.write("];\n")
print(len(runs), "runs ->", out)
